CREATE TABLE aura_motion_jobs (
 id CHAR(36) NOT NULL PRIMARY KEY,
 owner_id CHAR(36) NOT NULL,
 piece_id CHAR(36) NOT NULL,
 request_key CHAR(36) NOT NULL,
 piece_revision BIGINT NOT NULL,
 source_url VARCHAR(2048) NOT NULL,
 source_hash VARCHAR(64) NOT NULL,
 context_json JSON NOT NULL,
 template_id VARCHAR(40) NOT NULL,
 consented_at TIMESTAMP(6) NOT NULL,
 status VARCHAR(20) NOT NULL,
 provider_job_id VARCHAR(200),
 media_url VARCHAR(2048),
 failure_code VARCHAR(80),
 submitted_at TIMESTAMP(6),
 attempts INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP(6) NOT NULL,
 updated_at TIMESTAMP(6) NOT NULL,
 created_by VARCHAR(80),
 last_modified_by VARCHAR(80),
 version BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT fk_aura_motion_owner FOREIGN KEY(owner_id) REFERENCES users(id) ON DELETE CASCADE,
 CONSTRAINT fk_aura_motion_piece FOREIGN KEY(piece_id) REFERENCES wardrobe_items(id) ON DELETE CASCADE,
 CONSTRAINT uq_aura_motion_request UNIQUE(owner_id,request_key),
 KEY idx_aura_motion_queue(status,created_at),
 KEY idx_aura_motion_owner(owner_id,created_at)
);
