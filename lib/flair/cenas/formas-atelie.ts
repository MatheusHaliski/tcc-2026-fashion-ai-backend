/** Contorno de roda dentada: n dentes entre o raio de dentro e o de fora. */
function dentada(n: number, dentro: number, fora: number): number[] {
  const pts: number[] = [];
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2;
    const passo = (Math.PI * 2) / n;
    for (const [da, r] of [[0, dentro], [passo * 0.18, fora], [passo * 0.5, fora], [passo * 0.68, dentro]] as const) {
      pts.push(Math.round(Math.cos(a + da) * r * 1000) / 1000, Math.round(Math.sin(a + da) * r * 1000) / 1000);
    }
  }
  return pts;
}

